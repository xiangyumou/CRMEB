import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const source = fs.readFileSync(path.resolve('template/uni-app/utils/wechatPayment.js'));
const { requestMiniProgramPayment, requestWechatBrowserPayment, redirectExternalBrowserPayment } = await import(`data:text/javascript;base64,${source.toString('base64')}`);
const jsConfig = { timestamp: '123', nonceStr: 'nonce', package: 'prepay_id=1', signType: 'MD5', paySign: 'signature' };
let called;
globalThis.uni = { requestPayment: options => { called = ['requestPayment', options]; } };
requestMiniProgramPayment(jsConfig, { success: () => {} });
assert.equal(called[0], 'requestPayment');
assert.deepEqual(Object.keys(called[1]).sort(), ['timeStamp', 'nonceStr', 'package', 'signType', 'paySign', 'success'].sort());
assert.equal(called[1].timeStamp, '123');
globalThis.uni.requestOrderPayment = options => { called = ['requestOrderPayment', options]; };
requestMiniProgramPayment(jsConfig, {});
assert.equal(called[0], 'requestOrderPayment');
const result = Promise.resolve('paid');
assert.equal(requestWechatBrowserPayment({ pay: config => { assert.equal(config, jsConfig); return result; } }, jsConfig), result);
globalThis.location = { href: '' };
globalThis.setTimeout = (callback, delay) => { assert.equal(delay, 1500); callback(); };
redirectExternalBrowserPayment('https://example.test/pay');
assert.equal(globalThis.location.href, 'https://example.test/pay');
console.log('Mini-program, WeChat H5 and external H5 payment adapters: OK');
