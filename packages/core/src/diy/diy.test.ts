/**
 * The fixtures live in `@shop/contracts` because that is where the schemas
 * that describe them live, and duplicating half a megabyte of production JSON
 * into a second package to avoid a relative path would be worse.
 */
const CONTRACT_FIXTURES = path.join(
  import.meta.dirname,
  '..',
  '..',
  '..',
  'contracts',
  'src',
  'diy',
  '__fixtures__',
);

function fixture<T = Record<string, unknown>>(name: string): T {
  return JSON.parse(readFileSync(path.join(CONTRACT_FIXTURES, name), 'utf8')) as T;
}

function pageValueOf(row: { value: unknown }): Record<string, unknown> {
  return typeof row.value === 'string'
    ? (JSON.parse(row.value) as Record<string, unknown>)
    : (row.value as Record<string, unknown>);
}

